import uuid
from django.db import models
from apps.profiles.models import UserProfile
from apps.opportunities.models import Opportunity


class Recommendation(models.Model):
    """
    Candidate recommendation instance generated by the deterministic hybrid ranking engine.
    Every factor is normalized to 0-100 and strictly grounded in backend calculations.
    """
    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    profile = models.ForeignKey(UserProfile, on_delete=models.CASCADE, related_name='recommendations')
    opportunity = models.ForeignKey(Opportunity, on_delete=models.CASCADE, related_name='recommended_to')
    
    # Normalized Factor Scores (0.00 to 100.00)
    overall_score = models.DecimalField(max_digits=5, decimal_places=2, help_text="Weighted final composite score (0-100)")
    semantic_score = models.DecimalField(max_digits=5, decimal_places=2, default=0.00)
    skill_score = models.DecimalField(max_digits=5, decimal_places=2, default=0.00)
    role_score = models.DecimalField(max_digits=5, decimal_places=2, default=0.00)
    experience_score = models.DecimalField(max_digits=5, decimal_places=2, default=0.00)
    location_score = models.DecimalField(max_digits=5, decimal_places=2, default=0.00)
    preference_score = models.DecimalField(max_digits=5, decimal_places=2, default=0.00)
    
    # Hard Filter Status
    passed_hard_filters = models.BooleanField(default=True, help_text="Whether opportunity satisfied all active dealbreakers")
    exclusion_reasons = models.JSONField(default=list, blank=True, help_text="Specific dealbreakers violated if excluded")
    
    calculated_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        db_table = 'matchforge_recommendations'
        unique_together = ('profile', 'opportunity')
        verbose_name = 'Recommendation'
        verbose_name_plural = 'Recommendations'
        ordering = ['-overall_score', '-calculated_at']
        indexes = [
            models.Index(fields=['profile', '-overall_score']),
            models.Index(fields=['profile', 'passed_hard_filters']),
        ]

    def __str__(self):
        status = "PASSED" if self.passed_hard_filters else "EXCLUDED"
        return f"{self.profile.user.username} -> {self.opportunity.title}: {self.overall_score}% ({status})"


class RecommendationExplanation(models.Model):
    """
    Factual, evidence-grounded explanation for a recommendation.
    Derived purely from computed match evidence to prevent hallucination.
    """
    recommendation = models.OneToOneField(Recommendation, on_delete=models.CASCADE, primary_key=True, related_name='explanation')
    matched_skills = models.JSONField(default=list, help_text="Skills found in both candidate and job requirements")
    missing_skills = models.JSONField(default=list, help_text="Skills required by job but absent from candidate")
    preference_matches = models.JSONField(default=list, help_text="Preferences satisfied e.g. 'Remote work mode', 'Stipend available'")
    potential_concerns = models.JSONField(default=list, help_text="Any discrepancies e.g. 'Experience slightly below preferred target'")
    natural_language_explanation = models.TextField(blank=True, default='')
    generated_at = models.DateTimeField(auto_now=True)

    class Meta:
        db_table = 'matchforge_recommendation_explanations'
        verbose_name = 'Recommendation Explanation'
        verbose_name_plural = 'Recommendation Explanations'

    def __str__(self):
        return f"Explanation for Rec {self.recommendation.id}"
